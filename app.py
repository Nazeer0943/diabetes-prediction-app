
import streamlit as st
import pandas as pd
import joblib

st.set_page_config(
    page_title="Diabetes Prediction App",
    page_icon="🩺",
    layout="wide"
)

# Load the trained model
model = joblib.load("diabetes_model.joblib")

st.title("🩺 Diabetes Prediction App")
st.write(
    "Enter the information below to explore a diabetes "
    "classification model. This is a learning demonstration, "
    "not a medical diagnosis."
)

st.subheader("Personal Information")

age = st.number_input(
    "Age",
    min_value=1,
    max_value=120,
    value=40
)

gender = st.selectbox(
    "Gender",
    ["Male", "Female"]
)
ismale = 1 if gender == "Male" else 0

# Symptoms and characteristics
symptoms = [
    "polyuria",
    "polydipsia",
    "sudden weight loss",
    "weakness",
    "polyphagia",
    "genital thrush",
    "visual blurring",
    "itching",
    "irritability",
    "delayed healing",
    "partial paresis",
    "muscle stiffness",
    "alopecia",
    "obesity"
]

st.subheader("Symptoms and Other Characteristics")

answers = {}

for symptom in symptoms:
    answer = st.selectbox(
        symptom.replace("_", " ").title(),
        ["No", "Yes"],
        key=symptom
    )
    answers[symptom] = 1 if answer == "Yes" else 0

# Keep the exact feature order used during training
feature_names = [
    "age",
    "ismale",
    "polyuria",
    "polydipsia",
    "sudden weight loss",
    "weakness",
    "polyphagia",
    "genital thrush",
    "visual blurring",
    "itching",
    "irritability",
    "delayed healing",
    "partial paresis",
    "muscle stiffness",
    "alopecia",
    "obesity"
]

if st.button("Predict"):
    input_values = [
        age,
        ismale,
        *[answers[name] for name in feature_names[2:]]
    ]

    input_data = pd.DataFrame(
        [input_values],
        columns=feature_names
    )

    prediction = model.predict(input_data)[0]

    st.subheader("Prediction Result")
    st.write(f"Predicted class: {prediction}")
    st.caption(
        "This output is generated by a practice model "
        "and must not be used for medical decisions."
    )
